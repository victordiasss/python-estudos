# Crie um algoritmo que leia um número e mostre o seu dobro, o triplo e raiz quadrada.

numero = int(input('Digite um número:'))

dobro = numero * 2
triplo = numero * 3
raiz = numero ** (1/2)

print(f'O dobro de {numero} é {dobro}, o triplo de {numero} é {triplo} e a raiz quadrada de {numero} é {raiz}')
